import assert from "node:assert/strict";
import { PlayerPriceReviewTestFixtures } from "./PlayerPriceReviewTestFixtures.js";
import { PlayerPriceReviewService } from "./PlayerPriceReviewService.js";
import { PlayerPriceReviewContextResolver } from "./PlayerPriceReviewContextResolver.js";
import { PlayerPriceReviewMatchSelector } from "./PlayerPriceReviewMatchSelector.js";
import { PlayerPricePerformanceCalculator } from "./PlayerPricePerformanceCalculator.js";
import { PlayerPriceRecommendationCalculator } from "./PlayerPriceRecommendationCalculator.js";

const fixtures = new PlayerPriceReviewTestFixtures();
const scenario = fixtures.createScenario();
const context = new PlayerPriceReviewContextResolver().resolveContext(scenario.calendar, scenario.now);
assert.deepEqual(context.tours.map((tour) => tour.id), ["tour-10", "tour-9"]);
assert.equal(new PlayerPriceReviewContextResolver().resolveContext(scenario.calendar, new Date("2026-07-01")).tours.length, 0);
const data = { matches: new PlayerPriceReviewMatchSelector().selectFinishedMatches(scenario.database.matches, context), playerStats: scenario.database.playerStats };
const calculator = new PlayerPricePerformanceCalculator();
const performances = scenario.players.map((player) => calculator.calculatePerformance(player, context, data));
const evaluator = new PlayerPriceRecommendationCalculator();
assert.equal(evaluator.evaluateRecommendation(performances[0], performances).suggestedPrice, 11);
assert.equal(evaluator.evaluateRecommendation(performances[1], performances).suggestedPrice, 9);
assert.equal(evaluator.evaluateRecommendation(performances[2], performances).reason, "unchanged");
assert.equal(evaluator.evaluateRecommendation({ ...performances[0], count: 2 }, performances).reason, "insufficient");
assert.equal(evaluator.evaluateRecommendation({ ...performances[0], count: 3 }, performances).reason, "recommendation");
assert.equal(evaluator.evaluateRecommendation(performances[0], performances.slice(0, 3)).reason, "peers");
const foreignPeers = performances.map((item) => ({ ...item, player: { ...item.player, team: "МХК Авто", id: `foreign-${item.player.id}`, price: 1 } }));
assert.equal(evaluator.evaluateRecommendation(performances[0], [...performances, ...foreignPeers]).suggestedPrice, 11);
const goalkeeper = { ...performances[0], player: { ...performances[0].player, position: "вратарь" } };
assert.equal(evaluator.evaluateRecommendation({ ...goalkeeper, count: 2 }, [goalkeeper]).reason, "insufficient");
assert.equal(evaluator.evaluateRecommendation(goalkeeper, [goalkeeper]).reason, "peers");
const goaliePeer = { ...performances[2], player: { ...performances[2].player, position: "вратарь" } };
assert.equal(evaluator.evaluateRecommendation(goalkeeper, [goalkeeper, goaliePeer]).suggestedPrice, 11);
const report = await new PlayerPriceReviewService(fixtures.createRepositories(scenario)).createReviewReport();
assert.equal(report.recommendations.length, 1, "Incomplete catalogue must block raises, but allow reductions");
assert.equal(report.counts.budget, 1);
assert.equal(report.counts.unchanged, 3);
assert(report.coverage.every((item) => item.sufficient));
const before = JSON.stringify(scenario);
await new PlayerPriceReviewService(fixtures.createRepositories(scenario)).createReviewReport();
assert.equal(JSON.stringify(scenario), before, "Review must not mutate data");
const missing = fixtures.createScenario();
missing.database.matches = missing.database.matches.filter((match) => !match.id.includes("-10-"));
const blocked = await new PlayerPriceReviewService(fixtures.createRepositories(missing)).createReviewReport();
assert.equal(blocked.recommendations.length, 0);
assert.equal(blocked.counts.coverage, 5);
console.log("Player price review domain self-test passed");
