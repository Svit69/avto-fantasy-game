import assert from "node:assert/strict";
import { TourResultMessageFactory } from "./TourResultMessageFactory.js";
import { TelegramUserMapper } from "./TelegramUserMapper.js";
import { UserEntity } from "./UserEntity.js";
const factory = new TourResultMessageFactory();
const leader = { userId: "123", name: "Анна <Иванова> & Co", place: 1, points: 186, username: "manager_1", phone: "+79991234567", email: "anna@example.test" };
const result = { title: "Ноябрьский тур", leaders: [leader] };
const winner = factory.createWinnerMessage(result, leader);
assert(winner.includes("1-е место") && winner.includes("186 ФО"));
assert(winner.includes("&lt;Иванова&gt; &amp;"));
assert(!winner.includes(leader.phone) && !winner.includes(leader.email), "Private contact data must not be sent to the winner");
const admin = factory.createAdminMessages(result).join("\n");
assert(admin.includes(leader.phone) && admin.includes(leader.email) && admin.includes("@manager_1"));
assert(admin.includes('href="tg://user?id=123"'));
assert(factory.createWinnerMessage({ ...result, leaders: [leader, { ...leader, userId: "456" }] }, leader).includes("разделили"));
assert(factory.createAdminMessages({ ...result, leaders: [{ ...leader, phone: "", email: "", username: "" }] })[0].includes("не указан"));
const many = Array.from({ length: 100 }, (_, index) => ({ ...leader, userId: String(index + 1), name: "&".repeat(200), phone: "<".repeat(200), email: ">".repeat(200) }));
const parts = factory.createAdminMessages({ title: "&".repeat(200), leaders: many });
assert(parts.length > 1 && parts.every((text) => text.length <= 4096));
assert(factory.createAdminMessages({ ...result, leaders: [] })[0].includes("Участников"));
assert(factory.createPendingMessage({ title: "Тур" }, []).includes("В календаре нет матчей"));
const profile = new TelegramUserMapper().createUserFromTelegramProfile({ id: 123, first_name: "Анна", username: "manager_1" });
assert.equal(new UserEntity(profile.toJSON()).username, "manager_1");
assert.equal(profile.mergeProfile({ username: "new_handle" }).username, "new_handle");
assert.equal(profile.mergeProfile({ username: "" }).username, "");
assert.equal(new UserEntity({ id: 1 }).username, "");
console.log("Tour winner text, admin-only contacts, ties and Telegram message size self-test passed");
