import assert from "node:assert/strict";
import { TourSchedulePolicy } from "../src/services/TourSchedulePolicy.js";
import { MonthSelectAvailabilityController } from "../src/controllers/MonthSelectAvailabilityController.js";
import { InitialTourSelectionService } from "../src/services/InitialTourSelectionService.js";
import { HeaderView } from "../src/views/HeaderView.js";
import { RosterDeadlineGuard } from "./RosterDeadlineGuard.js";
import { createTourLoadingFixture } from "./tour-loading-test-fixture.js";

const { calendar, now } = createTourLoadingFixture(); const policy = new TourSchedulePolicy();
const options = ["past", "current", "next", "closed", "unknown"].map((value) => ({ value, dataset: {} }));
const select = { value: "past", options }; const root = { querySelector: () => select, querySelectorAll: () => options };
const client = { loadFantasyCalendar: async () => calendar };
const availability = new MonthSelectAvailabilityController(root, client, policy);
await availability.applyAvailableTourOptions();
assert.equal(options[2].disabled, false); assert.equal(options[3].disabled, true); assert.equal(options[4].disabled, true);
assert.equal(select.disabled, false); assert.match(new HeaderView().render(), /aria-label="Выбрать месяц" disabled/);
client.loadFantasyCalendar = async () => { throw new Error("offline"); };
await assert.rejects(availability.applyAvailableTourOptions(), /offline/);
assert.equal(select.disabled, true); assert.ok(options.every((option) => option.disabled));
const invalid = { ...calendar, tours: [...calendar.tours, { month: "broken", deadlineAt: "invalid" }] };
assert.ok(policy.buildTourAccessStates(invalid, now).every((state) => !state.isOpen && state.isLocked));
assert.equal(policy.findTourAccessState(calendar, "unknown").isOpen, false);
const selector = new InitialTourSelectionService({ loadFantasyCalendar: async () => calendar }, { loadSavedRoster: async () => null }, policy);
await selector.applyInitialTourSelection(select, now); assert.equal(select.value, "next");
selector.rosterApiClient.loadSavedRoster = async () => ({ slots: Array.from({ length: 6 }, () => ({ playerId: "p" })) });
await selector.applyInitialTourSelection(select, now); assert.equal(select.value, "current");
selector.rosterApiClient.loadSavedRoster = async () => { throw new Error("roster_offline"); };
await assert.rejects(selector.applyInitialTourSelection(select, now), /roster_offline/);
const guard = new RosterDeadlineGuard({ listCalendar: async () => calendar });
assert.equal(await guard.canModifyRoster("closed"), false); assert.equal(await guard.canModifyRoster("next"), true);
console.log("Tour unknown-month denial, invalid deadlines, initial selection and backend deadline guard self-test passed");
