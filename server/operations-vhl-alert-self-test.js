import assert from "node:assert/strict";
import { WorkerHeartbeat } from "./WorkerHeartbeat.js";
import { VhlWorkerAlertCondition } from "./VhlWorkerAlertCondition.js";
import { OperationalAlertDispatcher } from "./OperationalAlertDispatcher.js";

let state = null;
const store = { readState: async () => state, writeState: async (_name, value) => { state = value; } };
const condition = () => new VhlWorkerAlertCondition().createCondition(state);
const messages = [];
const alerts = new OperationalAlertDispatcher({ hasToken: () => true, callJson: async (_method, message) => { messages.push(message.text); return { ok: true }; } }, { warn: () => {} }, ["1"]);
let heartbeat = new WorkerHeartbeat(store);
const fail = async () => [{ ok: false, matchId: "match-1", reason: "vhl_online_http_502" }];
await heartbeat.recordCycle(fail);
assert.equal(state.consecutiveFailedCycles, 1);
assert.equal(condition().active, false);
await alerts.dispatchAlerts([condition()], 0);
await alerts.dispatchAlerts([condition()], 120000);
assert.equal(messages.length, 0, "A single failure must not trigger an alert while awaiting the next cycle");
await heartbeat.recordCycle(async () => []);
assert.equal(state.consecutiveFailedCycles, 0);
assert.deepEqual(state.lastFailures, []);
await heartbeat.recordCycle(fail);
await heartbeat.recordCycle(fail);
assert.equal(condition().active, false);
heartbeat = new WorkerHeartbeat(store);
await heartbeat.recordCycle(fail);
assert.equal(state.consecutiveFailedCycles, 3, "Failure streak must survive worker recreation");
assert.equal(condition().active, true);
assert(condition().text.includes("5xx"));
await alerts.dispatchAlerts([condition()], 240000);
await alerts.dispatchAlerts([condition()], 255000);
assert.equal(messages.length, 1);
await heartbeat.recordCycle(async () => [{ ok: true }]);
await alerts.dispatchAlerts([condition()], 260000);
await alerts.dispatchAlerts([condition()], 321000);
assert.equal(messages.length, 2);
assert(messages[1].includes("ВХЛ: опрос снова проходит без ошибок"));
await assert.rejects(heartbeat.recordCycle(async () => { throw Error("offline"); }), /offline/);
assert.equal(state.consecutiveFailedCycles, 1);
assert.equal(condition().active, false);
assert.equal(new VhlWorkerAlertCondition().createCondition({ failedMatches: 1 }).holdMs, 300000);
console.log("VHL consecutive failure alert and recovery self-test passed");
