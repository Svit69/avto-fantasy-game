import assert from "node:assert/strict";
import { PriceReviewRosterOptimizer } from "./PriceReviewRosterOptimizer.js";
import { PlayerPriceBudgetPolicy } from "./PlayerPriceBudgetPolicy.js";
import { FANTASY_ROSTER_RULES } from "../src/config/FantasyRosterRules.js";

const positions = ["нападающий", "нападающий", "нападающий", "защитник", "защитник", "вратарь"];
const players = ["КХЛ", "ВХЛ"].flatMap((team, group) => positions.map((position, index) => ({ id: `${team}-${index}`, team, position, price: group ? 10 : 20 })));
const optimizer = new PriceReviewRosterOptimizer();
const cheapest = optimizer.findOptimalRoster(players);
assert.equal(cheapest.cost, 80, "Respect club cap even when all cheapest players belong to same club");
assert.equal(cheapest.players.length, 6);
assert.equal(cheapest.players.filter((player) => player.position === "вратарь").length, 1);
assert.equal(optimizer.findOptimalRoster(players.filter((player) => player.team === "КХЛ")), null);
const relaxed = new PriceReviewRosterOptimizer({ ...FANTASY_ROSTER_RULES, clubPlayerLimit: 6 });
assert.equal(relaxed.findOptimalRoster(players).cost, 60);
const performances = players.map((player) => ({ player, forecast: player.price * 2, count: 10 }));
const policy = new PlayerPriceBudgetPolicy();
const budget = policy.createBudgetContext(performances);
assert.equal(budget.limit, FANTASY_ROSTER_RULES.budgetLimit);
assert.equal(budget.referencePoints, 200);
assert.equal(budget.minimumBefore, 80);
const fair = policy.calculateFairPrice(performances[0], 20, budget);
assert.equal(fair, 19.2);
assert(policy.calculateFairPrice(performances[0], 20, { ...budget, limit: 60 }) < fair);
assert.equal(policy.calculateFairPrice(performances[0], 20, { ...budget, referencePoints: null }), 20);
players[0].price = 29;
assert.equal(optimizer.findOptimalRoster(players, undefined, players[0].id).cost, 89);
const proposals = [{ reason: "recommendation", player: players[0], suggestedPrice: 30 },
  ...players.filter((player) => player.team === "ВХЛ").map((player) => ({ reason: "recommendation", player, suggestedPrice: 11 }))];
const individual = policy.protectAffordability(proposals.slice(0, 1), performances, budget);
assert.equal(individual.evaluations[0].reason, "recommendation", "Exactly 90k is affordable");
const combined = policy.protectAffordability(proposals, performances, budget);
assert.equal(combined.evaluations[0].reason, "budget", "All proposed changes must be checked together");
assert.equal(combined.evaluations[1].reason, "recommendation");
assert(combined.budget.minimumAfter <= 90);
const overpriced = performances.map((item) => ({ ...item, player: { ...item.player, price: 100 } }));
const reduction = { reason: "recommendation", player: overpriced[0].player, suggestedPrice: 99 };
assert.equal(policy.protectAffordability([reduction], overpriced, budget).evaluations[0].reason, "recommendation");
console.log("Player price review budget self-test passed");
