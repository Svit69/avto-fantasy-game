import assert from "node:assert/strict";
import { PlayerPriceReviewTestFixtures } from "./PlayerPriceReviewTestFixtures.js";
import { PlayerPriceReviewContextResolver } from "./PlayerPriceReviewContextResolver.js";
import { PlayerPriceReviewDataSource } from "./PlayerPriceReviewDataSource.js";
import { PlayerPricePerformanceCalculator } from "./PlayerPricePerformanceCalculator.js";
import { PriceReviewCoverageCalculator } from "./PriceReviewCoverageCalculator.js";
import { PlayerPriceReviewService } from "./PlayerPriceReviewService.js";

const fixtures = new PlayerPriceReviewTestFixtures();
const scenario = fixtures.createScenario();
scenario.calendar.matches.push({ ...scenario.calendar.matches[0], id: "future", startsAt: "2026-10-20T10:00:00Z", gameId: "future" });
scenario.database.matches.push({ ...scenario.database.matches[0], id: "future", gameId: "future", scheduledAt: "2026-10-20T10:00:00Z", status: "finished" });
const context = new PlayerPriceReviewContextResolver().resolveContext(scenario.calendar, scenario.now);
const data = await new PlayerPriceReviewDataSource({ readDatabase: async () => scenario.database }).readReviewData(context);
assert(!data.matches.some((match) => match.id === "future"));
const coverageCalculator = new PriceReviewCoverageCalculator();
const partial = { ...data, matches: data.matches.filter((match) => !match.id.includes("-10-0") && !match.id.includes("-10-1")) };
assert(coverageCalculator.calculateTeamCoverage("Автомобилист", context, partial).sufficient, "Exactly 80% coverage is allowed");
assert(!coverageCalculator.calculateTeamCoverage("Автомобилист", context, { matches: data.matches, playerStats: [] }).sufficient, "Empty protocols do not count as loaded");
const calculator = new PlayerPricePerformanceCalculator();
const weightedStats = data.playerStats.map((stat) => ({ ...stat, fantasyPoints: stat.matchId.includes("-10-") ? 40 : 10 }));
const performance = calculator.calculatePerformance(scenario.players[0], context, { ...data, playerStats: weightedStats });
assert(Math.abs(performance.forecast - performance.recentForm.adjustment - 32.5) < 0.000001, "Use rolling 5/10/season windows separately from recent form");
const sparse = calculator.calculatePerformance(scenario.players[0], context, { ...data, playerStats: [weightedStats[0]] });
assert.equal(sparse.count, 1);
assert(Math.abs(sparse.forecast - 10) < 0.000001, "Missing current tour does not lower older points to zero");
scenario.players.push({ ...scenario.players[0], id: "left", status: "left_game" });
const report = await new PlayerPriceReviewService(fixtures.createRepositories(scenario)).createReviewReport();
assert.equal(report.total, 5);
assert(!report.recommendations.some((item) => item.player.id === "left"));
console.log("Player price review edge self-test passed");
